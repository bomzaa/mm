// Helper queries with strict grade isolation
export function getCurriculumByGrade(gradeLevel: GradeLevel): SubjectItem[] {
  return CURRICULUM_DATA[gradeLevel] || [];
}

export function getCategoriesForGrade(gradeLevel: GradeLevel): SubjectCategory[] {
  const subjects = getCurriculumByGrade(gradeLevel);
  const categoriesSet = new Set<SubjectCategory>();
  subjects.forEach((s) => categoriesSet.add(s.category));
  return Array.from(categoriesSet);
}

export function getSubjectsByGradeAndCategory(
  gradeLevel: GradeLevel,
  category?: SubjectCategory
): SubjectItem[] {
  const subjects = getCurriculumByGrade(gradeLevel);
  if (!category) return subjects;
  return subjects.filter((s) => s.category === category);
}

export function getSubjectById(
  gradeLevel: GradeLevel,
  subjectId: string
): SubjectItem | undefined {
  const subjects = getCurriculumByGrade(gradeLevel);
  return subjects.find((s) => s.id === subjectId || s.name === subjectId);
}

// Strict Grade Validator Rule: Question.gradeLevel === ExpectedGradeLevel
export function validateQuestionGrade(
  question: Partial<Question>,
  expectedGrade: GradeLevel
): boolean {
  if (!question) return false;
  return question.gradeLevel === expectedGrade;
}
